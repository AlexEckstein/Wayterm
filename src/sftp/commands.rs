//! The command vocabulary shared between the GTK sidebar and the SFTP task.

use tokio::sync::{mpsc, oneshot};

/// One progress sample from a running transfer (doc 09 §Transfers).
///
/// Sent with `try_send`; a sample is dropped rather than blocking the
/// transfer — a stale-but-moving progress bar is fine, a stalled tokio
/// task is not.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Progress {
    pub transferred: u64,
    pub total: u64,
}

/// One entry of a directory listing, formatted for display (doc 09).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DirEntry {
    pub name: String,
    pub size: u64,
    /// `YYYY-MM-DD HH:MM` (UTC), or empty when the server sent no mtime.
    pub modified: String,
    /// `rwxr-xr-x`-style permission bits, or empty when unknown.
    pub permissions: String,
    pub is_dir: bool,
}

/// Commands sent to the SFTP task (doc 09 §Connection Model).
///
/// Every variant except `Cancel` carries a oneshot reply, and the task
/// answers exactly once — including with `Err` when the SFTP session is
/// dead, which is how the sidebar observes a closed subsystem (doc 09:
/// "the next command's oneshot reply errors").
///
/// Phase-3 adaptation of the doc 09 sketch: `Download`/`Upload` carry a
/// `transfer_id` pre-generated by the UI ([`SftpClient::next_transfer_id`])
/// so a later `Cancel { transfer_id }` can match the running transfer.
///
/// [`SftpClient::next_transfer_id`]: crate::sftp::SftpClient::next_transfer_id
pub enum SftpCommand {
    Cd {
        path: String,
        reply: oneshot::Sender<Result<Vec<DirEntry>, String>>,
    },
    Download {
        transfer_id: u64,
        remote_path: String,
        local_path: String,
        progress: mpsc::Sender<Progress>,
        reply: oneshot::Sender<Result<u64, String>>,
    },
    Upload {
        transfer_id: u64,
        local_path: String,
        remote_path: String,
        progress: mpsc::Sender<Progress>,
        reply: oneshot::Sender<Result<u64, String>>,
    },
    Delete {
        path: String,
        reply: oneshot::Sender<Result<(), String>>,
    },
    Rename {
        from: String,
        to: String,
        reply: oneshot::Sender<Result<(), String>>,
    },
    Mkdir {
        path: String,
        reply: oneshot::Sender<Result<(), String>>,
    },
    Cancel {
        transfer_id: u64,
    },
}
